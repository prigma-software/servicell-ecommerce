// ============================================

/**
 * Returns the count of active (pending) stock reservations.
 */
export async function countActiveReservations(client: SupabaseClient) {
  const { count, error } = await client
    .from("stock_reservations")
    .select("*", { count: "exact", head: true })
    .eq("status", "pending")

  if (error) throw new Error(error.message)
  return count ?? 0
}

// ============================================
// RPCs — Reservations
// ============================================

/**
 * Calls the DB function that expires all timed-out reservations globally.
 */
export async function cleanupExpiredReservations(client: SupabaseClient) {
  const { error } = await client.rpc("cleanup_expired_reservations")
  if (error) throw new Error(error.message)
}

/**
 * Calls the DB function that expires reservations for a specific product.
 */
export async function cleanupExpiredReservationsForProduct(
  client: SupabaseClient,
  productId: string
) {
  const { error } = await client.rpc(
    "cleanup_expired_reservations_for_product",
    { p_product_id: productId }
  )
  if (error) throw new Error(error.message)
}

/**
 * Creates a stock reservation for a set of cart items.
 * Returns the reservation ID generated by the DB.
 */
export async function createStockReservation(
  client: SupabaseClient,
  userId: string,
  items: unknown,
  reservationMinutes: number = 15
) {
  const { data, error } = await client.rpc("create_stock_reservation", {
    p_user_id: userId,
    p_items: items as any,
    p_reservation_minutes: reservationMinutes,
  })

  if (error) throw new Error(error.message)
  return data
}

