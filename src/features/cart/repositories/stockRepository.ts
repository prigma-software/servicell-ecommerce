import type { SupabaseClient } from "@supabase/supabase-js"

// ============================================
// READ — SKUs & Products
// ============================================

/**
 * Returns SKU records by a list of IDs.
 * Includes stock, active status, price override, and parent product ID.
 */
export async function findSkusByIds(client: SupabaseClient, ids: string[]) {
  if (ids.length === 0) return []

  const { data, error } = await client
    .from("product_skus")
    .select("id, stock, active, product_id, price_override, sku_code")
    .in("id", ids)

  if (error) throw new Error(error.message)
  return data ?? []
}

/**
 * Returns product records by a list of IDs.
 * Includes stock, active, archived status, and price.
 */
export async function findProductsByIds(client: SupabaseClient, ids: string[]) {
  if (ids.length === 0) return []

  const { data, error } = await client
    .from("products")
    .select("id, stock, active, archived, price")
    .in("id", ids)

  if (error) throw new Error(error.message)
  return data ?? []
}

/**
 * Returns products by ID list including the reservation flag.
 * Used for cart validation to detect products with active reservations.
 */
export async function findProductsWithReservationFlag(
  client: SupabaseClient,
  ids: string[]
) {
  if (ids.length === 0) return []

  const { data, error } = await client
    .from("products")
    .select("id, name, price, stock, active, archived, has_active_reservation")
    .in("id", ids)

  if (error) throw new Error(error.message)
  return data ?? []
}

/**
 * Returns refreshed stock values for the given product IDs.
 * Called after expiring reservations to get up-to-date quantities.
 */
export async function findProductsStockByIds(
  client: SupabaseClient,
  ids: string[]
) {
  if (ids.length === 0) return []

  const { data, error } = await client
    .from("products")
    .select("id, stock")
    .in("id", ids)

  if (error) throw new Error(error.message)
  return data ?? []
}

/**
 * Returns a single product's archived status by its ID.
 */
export async function findProductArchivedStatus(
  client: SupabaseClient,
  productId: string
) {
  const { data, error } = await client
    .from("products")
    .select("archived")
    .eq("id", productId)
    .single()

  if (error) throw new Error(error.message)
  return data
}

