// ============================================

/**
 * Increments the stock of a SKU variant.
 * Used when rolling back a declined/failed order.
 */
export async function incrementSkuStock(
  client: SupabaseClient,
  skuId: string,
  quantity: number
) {
  const { error } = await client.rpc("increment_sku_stock", {
    p_sku_id: skuId,
    p_quantity: quantity,
  })

  if (error) throw new Error(error.message)
}

